#!/usr/bin/env bash
# Write the Homebrew formula for a published release to stdout.
#
#   scripts/brew-formula.sh <version> <SHA256SUMS.txt>  > Formula/lotel.rb
#
# The release workflow runs this and pushes the result to the tap repo
# (hamin/homebrew-tap), so `brew install hamin/tap/lotel` installs the same
# tarballs as scripts/install.sh, checked against the same sha256 sums.
set -euo pipefail

[ $# -eq 2 ] || { echo "usage: $0 <version> <SHA256SUMS.txt>" >&2; exit 1; }
v=${1#v}
sums=$2
repo=${LOTEL_REPO:-hamin/lotel}

sha() { # <platform>
    local s
    s=$(awk -v f="lotel-$v-$1.tar.gz" '$2 == f || $2 ~ ("/" f "$") { print $1; exit }' "$sums")
    [ -n "$s" ] || { echo "$sums has no entry for lotel-$v-$1.tar.gz" >&2; exit 1; }
    printf '%s' "$s"
}
url() { printf 'https://github.com/%s/releases/download/v%s/lotel-%s-%s.tar.gz' "$repo" "$v" "$v" "$1"; }

cat <<EOF
# Generated by scripts/brew-formula.sh in $repo for v$v. Do not edit by hand.
class Lotel < Formula
  desc "See what your coding agents did: OpenTelemetry in one binary, forgotten on schedule"
  homepage "https://lotel.io"
  version "$v"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$(url darwin-arm64)"
      sha256 "$(sha darwin-arm64)"
    end
    on_intel do
      url "$(url darwin-x86_64)"
      sha256 "$(sha darwin-x86_64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux-aarch64)"
      sha256 "$(sha linux-aarch64)"
    end
    on_intel do
      url "$(url linux-x86_64)"
      sha256 "$(sha linux-x86_64)"
    end
  end

  def install
    bin.install "bin/lotel"
    doc.install "README.md", "CHANGELOG.md"
    prefix.install "LICENSE", "NOTICE", "THIRD-PARTY-LICENSES", "licenses"
  end

  # brew services start lotel: data under $(brew --prefix)/var/lotel
  service do
    run [opt_bin/"lotel"]
    environment_variables LOTEL_DATA_DIR: var/"lotel"
    keep_alive true
    log_path var/"log/lotel.log"
    error_log_path var/"log/lotel.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/lotel --version")
  end
end
EOF
