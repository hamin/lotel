#!/usr/bin/env python3
"""Bake the certified style lab into the binary: crates/lotel/src/skin.rs.

One-way door: design/bakeoff owns the look; the app embeds its output. After
any change to build_c.py / build_d.py / skin-additions.css run:

    python3 design/bakeoff/build_d.py && python3 scripts/gen-skin.py

Assembly (order matters): remote font @imports first (CSS law), then the
shared base reset, the generated token blocks, the certified C stylesheet
(with the lab's Chrome-98 swaps), and the port additions for components the
bake-off pages never carried. The panel's option swatches style off
[label|a][data-p]; the lab only emitted label rules (radios), so the anchor
twins are duplicated here for the port's link-based panel.
"""
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAB = ROOT / "design" / "bakeoff" / "d-lab"
BUILD_D = ROOT / "design" / "bakeoff" / "build_d.py"
OUT = ROOT / "crates" / "lotel" / "src" / "skin.rs"

IMPORT_RE = re.compile(r"@import\s+url\((.*?)\);?\s*")


def labels_of(src: str, name: str) -> dict:
    tree = ast.parse(src)
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == name:
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in build_d.py")


def main() -> None:
    base = (LAB / "base.css").read_text()
    tokens = (LAB / "tokens-bench.css").read_text()
    page = (LAB / "home.html").read_text()
    inline = re.search(r"<style[^>]*>(.*?)</style>", page, re.S).group(1)
    additions = (ROOT / "design" / "bakeoff" / "skin-additions.css").read_text()

    # font @imports ride at the top; local ones get replaced by the inlined bodies
    remote = [m for m in IMPORT_RE.findall(inline) if "http" in m]
    css = "\n".join(f"@import url({u});" for u in remote)
    for body in (base, tokens, inline, additions):
        css += "\n" + IMPORT_RE.sub("", body)

    # the base's [data-slot] image-placeholder rules (the only :has()/color-mix
    # left) are dead weight here: lotel ships no data-slot elements
    css = re.sub(r"\[[^\]]*data-slot[^\]]*\][^{]*\{[^}]*\}\s*", "", css)

    # the port's panel options are <a> patches; twin the lab's label-only rules
    swatches = re.findall(r"\.pop label\[data-p=\"([\w-]+)\"\]\s*\.sw\.([abc])\s*\{([^}]*)\}",
                          inline)
    if not swatches:
        raise SystemExit("no palette swatch rules found; lab format changed")
    css += "\n" + "\n".join(
        f'.pop a[data-p="{p}"] .sw.{s} {{{body}}}' for p, s, body in swatches) + "\n"

    # comments are dead weight in a shipped binary — and lab notes about the
    # very syntax we police should not trip the guard as mere text
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

    # the binary's Chrome-98 promise: no modern-only color syntax ships, and
    # :has() survives only in the one C row-hover enhancer (decorative: 98
    # drops the rule, losing nothing load-bearing)
    for banned in ("oklch", "color-mix"):
        if banned in css:
            raise SystemExit(f"{banned} leaked into the shipped CSS")
    stray = re.sub(r"tbody:has\(a\)", "", css)
    if ":has(" in stray:
        raise SystemExit("a new :has() rule leaked into the shipped CSS")
    if '"##"' in css:
        raise SystemExit('raw-string terminator "##" in the CSS')

    dsrc = BUILD_D.read_text()
    pals = "\n".join(f'    ("{k}", "{v}"),' for k, v in labels_of(dsrc, "PAL_LABELS").items())
    fonts = "\n".join(f'    ("{k}", "{v}"),' for k, v in labels_of(dsrc, "FONT_LABELS").items())

    OUT.write_text(f"""//! GENERATED by scripts/gen-skin.py — do not hand-edit.
//! Source of truth: design/bakeoff (build_c.py + build_d.py + skin-additions.css).
//! Restyle flow: edit the lab, run `python3 design/bakeoff/build_d.py`,
//! then `python3 scripts/gen-skin.py`, rebuild.

/// The whole skin: base reset + the four brand palettes' token blocks
/// (attribute-mapped, all precomputed hex for the owner's Chrome 98) + the
/// certified component sheet + the port additions.
pub(crate) const CSS: &str = r##"
{css}
"##;

/// (value, label) per palette; value is the data-pal attribute and the
/// token-block key, label is what the settings panel shows.
pub(crate) const PALETTES: &[(&str, &str)] = &[
{pals}
];

/// (value, label) per type pairing; value is the data-font attribute.
pub(crate) const FONTS: &[(&str, &str)] = &[
{fonts}
];

/// The colourway choices: the data-scheme value and its panel label.
/// "system" follows the OS light/dark preference (shown as "auto").
pub(crate) const SCHEMES: &[(&str, &str)] =
    &[("system", "auto"), ("night", "night"), ("day", "day")];
""")
    print(f"skin.rs: {len(css)} bytes of CSS, {len(labels_of(dsrc, 'PAL_LABELS'))} palettes, "
          f"{len(labels_of(dsrc, 'FONT_LABELS'))} fonts")


if __name__ == "__main__":
    main()
